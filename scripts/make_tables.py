"""Auto-generate paper/tables.md from results/full/summary.csv."""
import sys
from pathlib import Path

sys.path.insert(0, "src")
import pandas as pd

NON_LLM_ARMS = ["pca", "iforest", "ocsvm", "deeplog", "semantic_knn", "supervised_lgbm"]


def md_table(df, cols, headers):
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    for _, row in df.iterrows():
        lines.append("| " + " | ".join(str(row[c]) for c in cols) + " |")
    return "\n".join(lines)


def main():
    df = pd.read_csv("results/full/summary.csv")

    out = ["# Tables\n", "<!-- auto-generated by scripts/make_tables.py from results/full/summary.csv -->\n",
           "Note: `deeplog` rows reflect the Step 11 corrected scoring (mean NLL, primary); "
           "see `results/full/addendum/deeplog_diagnosis/DIAGNOSIS.md` and `VERDICTS_v2.md` for the "
           "correction and its effect. The original (pre-registered) `deeplog` cells are preserved in "
           "`results/superseded/deeplog_v1/`, and `VERDICTS.md` reports the unchanged pre-registered verdicts.\n"]

    out.append("## Table 1: AUROC / AUPRC, mean +/- SD across 5 seeds, by dataset x split x arm\n")
    agg = (
        df[df.arm.isin(NON_LLM_ARMS)]
        .groupby(["dataset", "split", "arm"])
        .agg(auroc_mean=("auroc", "mean"), auroc_sd=("auroc", "std"),
             auprc_mean=("auprc", "mean"), auprc_sd=("auprc", "std"))
        .reset_index()
        .round(4)
    )
    agg["AUROC"] = agg["auroc_mean"].astype(str) + " +/- " + agg["auroc_sd"].fillna(0).astype(str)
    agg["AUPRC"] = agg["auprc_mean"].astype(str) + " +/- " + agg["auprc_sd"].fillna(0).astype(str)
    out.append(md_table(agg, ["dataset", "split", "arm", "AUROC", "AUPRC"],
                         ["Dataset", "Split", "Arm", "AUROC", "AUPRC"]))
    out.append("")

    out.append("## Table 2: Threshold leakage (F1_oracle - F1_val), CHRONO, mean across 5 seeds\n")
    sub = df[(df.split == "chrono") & (df.arm.isin(NON_LLM_ARMS))]
    leak = sub.groupby(["dataset", "arm"]).agg(
        f1_val_mean=("f1_val", "mean"), f1_oracle_mean=("f1_oracle", "mean"),
        gap_mean=("f1_leakage_gap", "mean"),
    ).reset_index().round(4)
    out.append(md_table(leak, ["dataset", "arm", "f1_val_mean", "f1_oracle_mean", "gap_mean"],
                         ["Dataset", "Arm", "F1_val", "F1_oracle", "Gap"]))
    out.append("")

    out.append("## Table 3: unseen_template_rate by dataset x split (mean across 5 seeds)\n")
    utr = df[df.arm == "pca"].groupby(["dataset", "split"])["unseen_template_rate"].mean().reset_index().round(4)
    out.append(md_table(utr, ["dataset", "split", "unseen_template_rate"],
                         ["Dataset", "Split", "Unseen template rate"]))
    out.append("")

    llm = df[df.arm == "llm_zeroshot"]
    if len(llm):
        out.append("## Table 4: llm_zeroshot (sample-based, seed 0 only, not in main ranking)\n")
        out.append(md_table(llm[["dataset", "split", "auroc", "auprc", "n_sample"]].round(4),
                             ["dataset", "split", "auroc", "auprc", "n_sample"],
                             ["Dataset", "Split", "AUROC", "AUPRC", "N sample"]))
        out.append("")

    Path("paper").mkdir(exist_ok=True)
    with open("paper/tables.md", "w") as f:
        f.write("\n".join(out))
    print("wrote paper/tables.md")


if __name__ == "__main__":
    main()
